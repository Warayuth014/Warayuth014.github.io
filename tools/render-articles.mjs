#!/usr/bin/env node
// Usage: node tools/render-articles.mjs
// Regenerates articles/<slug>/index.html, articles/index.html and content/articles/index.json
// from content/site.json + content/articles/*.json. Drafts (published:false) get no page.
// Any invalid article, or a hand-made page in the way: print errors, exit 1, write nothing.
// The Cloudflare Worker mirrors this logic using shared/render-article.js.
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync, existsSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { validateArticle } from '../shared/schema.js';
import { renderArticlePage, renderArticleList, articleIndex, GENERATED_MARKER } from '../shared/render-article.js';

const defaultRoot = resolve(fileURLToPath(new URL('..', import.meta.url)));

const isGenerated = (file) => existsSync(file) && readFileSync(file, 'utf8').includes(GENERATED_MARKER);

/** Renders everything under `root`. Throws Error(message with all problems) before writing anything. */
export function renderAll(root = defaultRoot) {
  const dataDir = join(root, 'content', 'articles');
  const outDir = join(root, 'articles');
  const site = JSON.parse(readFileSync(join(root, 'content', 'site.json'), 'utf8'));
  const files = readdirSync(dataDir).filter((f) => f.endsWith('.json') && f !== 'index.json').sort();

  const articles = [];
  const errors = [];
  for (const f of files) {
    let a;
    try {
      a = JSON.parse(readFileSync(join(dataDir, f), 'utf8'));
    } catch (e) {
      errors.push(`${f}: not valid JSON (${e.message})`);
      continue;
    }
    const v = validateArticle(a);
    if (!v.ok) v.errors.forEach((m) => errors.push(`${f}: ${m}`));
    else if (`${a.slug}.json` !== f) errors.push(`${f}: slug "${a.slug}" must match the file name`);
    else articles.push(a);
  }

  const published = articles.filter((a) => a.published);
  const slugs = new Set(published.map((a) => a.slug));
  const targets = [...published.map((a) => join(outDir, a.slug, 'index.html')), join(outDir, 'index.html')];
  for (const file of targets) {
    if (existsSync(file) && !isGenerated(file)) errors.push(`${file}: exists and was not generated by render-articles, refusing to overwrite`);
  }
  if (errors.length) throw new Error(errors.join('\n'));

  mkdirSync(outDir, { recursive: true });
  const written = [];
  for (const a of published) {
    mkdirSync(join(outDir, a.slug), { recursive: true });
    writeFileSync(join(outDir, a.slug, 'index.html'), renderArticlePage(a, site));
    written.push(a.slug);
  }
  writeFileSync(join(outDir, 'index.html'), renderArticleList(articles, site));
  writeFileSync(join(dataDir, 'index.json'), `${JSON.stringify(articleIndex(articles), null, 2)}\n`);

  // remove generated folders without a published article (deleted or turned into a draft)
  const removed = [];
  for (const d of readdirSync(outDir, { withFileTypes: true })) {
    if (!d.isDirectory() || slugs.has(d.name)) continue;
    if (isGenerated(join(outDir, d.name, 'index.html'))) {
      rmSync(join(outDir, d.name), { recursive: true, force: true });
      removed.push(d.name);
    }
  }
  return { written, removed };
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  try {
    const { written, removed } = renderAll();
    removed.forEach((s) => console.log(`removed articles/${s}/`));
    console.log(`rendered ${written.length} article(s)`);
  } catch (e) {
    console.error(e.message);
    process.exit(1);
  }
}
