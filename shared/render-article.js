// Pure module (no DOM, no Node globals): renders static article pages as HTML strings.
// Used by tools/render-articles.mjs, the Cloudflare Worker (on save) and the editor preview.
// validateArticle does not sanitise, so every body goes through sanitizeRichText here and
// every other field is escaped.
import { escapeHtml, sanitizeRichText } from './sanitize.js';
import { t } from './i18n.js';
import { safeAsset } from './schema.js';
import { THEME_PREPAINT } from './theme-prepaint.js';

export const SITE_ORIGIN = 'https://warayuth014.github.io';
export const GENERATED_MARKER = '<!-- generated by render-articles -->';

const FONT_HREF = 'https://fonts.googleapis.com/css2?family=IBM+Plex+Sans+Thai:wght@400;500;600&family=Space+Grotesk:wght@500;700&display=swap';
const FAVICON = 'data:image/svg+xml,%3Csvg xmlns=%27http://www.w3.org/2000/svg%27 viewBox=%270 0 32 32%27%3E%3Crect width=%2732%27 height=%2732%27 rx=%268%27 fill=%27%230b0f1d%27/%3E%3Ctext x=%2716%27 y=%2723%27 font-size=%2720%27 font-family=%27monospace%27 font-weight=%27700%27 text-anchor=%27middle%27 fill=%27%237cf3ff%27%3Ew_%3C/text%3E%3C/svg%3E';

const UI = {
  home: { th: 'หน้าแรก', en: 'Home' },
  articles: { th: 'บทความ', en: 'Articles' },
  switchTo: { th: 'Switch to English', en: 'เปลี่ยนเป็นภาษาไทย' },
  allArticles: { th: 'บทความทั้งหมด', en: 'All articles' },
  empty: { th: 'เร็ว ๆ นี้ ยังไม่มีบทความ', en: 'Coming soon, no articles yet' },
  emptyHint: { th: 'ไว้กลับมาดูใหม่นะครับ', en: 'Check back later.' },
  back: { th: 'กลับหน้าแรก', en: 'Back home' },
};

const both = (key) => `<span lang="th">${escapeHtml(UI[key].th)}</span><span lang="en">${escapeHtml(UI[key].en)}</span>`;

// Runs before first paint so English visitors never see the Thai text.
const PREPAINT = `(function(){var d=document.documentElement,l='en';try{var s=localStorage.getItem('lang');if(s==='th'||s==='en')l=s;else if(/^th/i.test(navigator.language||''))l='th'}catch(e){if(/^th/i.test(navigator.language||''))l='th'}d.lang=l;document.title=d.getAttribute('data-title-'+l)||document.title})();`;
const TOGGLE = `(function(){var b=document.getElementById('lang-toggle');if(!b)return;b.addEventListener('click',function(){var d=document.documentElement,l=d.lang==='th'?'en':'th';d.lang=l;try{localStorage.setItem('lang',l)}catch(e){}document.title=d.getAttribute('data-title-'+l)||document.title;b.setAttribute('aria-label',b.getAttribute('data-label-'+l)||'')})})();`;

const INLINE_CSS = 'html:lang(th) [lang="en"], html:lang(en) [lang="th"] { display: none; }';

const siteName = (site) => t(site?.hero?.name, 'en').trim() || t(site?.hero?.name, 'th').trim() || 'Warayuth Bunbanlu';

function sortedPublished(articles) {
  return (Array.isArray(articles) ? articles : [])
    .filter((a) => a && a.published === true && typeof a.slug === 'string')
    .sort((a, b) => {
      const d = String(b.date).localeCompare(String(a.date));
      return d !== 0 ? d : String(a.slug).localeCompare(String(b.slug));
    });
}

/** Published articles, newest first (ties by slug), as the small records the home page needs. */
export function articleIndex(articles) {
  return sortedPublished(articles).map((a) => ({
    slug: a.slug,
    title: a.title,
    summary: a.summary,
    tags: Array.isArray(a.tags) ? a.tags : [],
    cover: safeAsset(a.cover) || null,
    date: a.date,
  }));
}

function nav(site, current) {
  const name = escapeHtml(siteName(site).split(/\s+/)[0]);
  const cur = (k) => (current === k ? ' aria-current="page"' : '');
  return `<header class="site-nav">
    <a class="brand mono" href="/" aria-label="${name}">${name.toLowerCase()}<span class="cursor" aria-hidden="true">_</span></a>
    <nav class="nav-simple"><ul>
      <li><a href="/"${cur('home')}>${both('home')}</a></li>
      <li><a href="/articles/"${cur('articles')}>${both('articles')}</a></li>
    </ul></nav>
    <button class="lang-btn mono" id="lang-toggle" type="button" aria-label="${escapeHtml(UI.switchTo.th)}" data-label-th="${escapeHtml(UI.switchTo.th)}" data-label-en="${escapeHtml(UI.switchTo.en)}"><span lang="th">EN</span><span lang="en">TH</span></button>
  </header>`;
}

function page({ titleTh, titleEn, description, head, current, site, main }) {
  const name = siteName(site);
  const fullTh = `${titleTh} | ${name}`;
  const fullEn = `${titleEn} | ${name}`;
  return `<!doctype html>
${GENERATED_MARKER}
<html lang="th" data-title-th="${escapeHtml(fullTh)}" data-title-en="${escapeHtml(fullEn)}">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>${escapeHtml(fullTh)}</title>
${description ? `  <meta name="description" content="${escapeHtml(description)}">\n` : ''}  <meta name="theme-color" content="#0b0f1d">
  <link rel="icon" href="${FAVICON}">
  <script>${THEME_PREPAINT}</script>
${head}
  <link rel="preconnect" href="https://fonts.googleapis.com">
  <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
  <link rel="stylesheet" href="${FONT_HREF}">
  <link rel="stylesheet" href="/assets/css/site.css">
  <style>${INLINE_CSS}</style>
  <script>${PREPAINT}</script>
</head>
<body class="page-doc">
  ${nav(site, current)}
${main}
  <footer class="site-foot mono"><span>&copy; ${escapeHtml(name)}</span></footer>
  <script>${TOGGLE}</script>
  <script type="module" src="/assets/js/page-theme.js"></script>
</body>
</html>
`;
}

function tagList(tags) {
  const items = (Array.isArray(tags) ? tags : []).filter((x) => typeof x === 'string' && x !== '');
  return items.length ? `<ul class="tags">${items.map((x) => `<li>${escapeHtml(x)}</li>`).join('')}</ul>` : '';
}

export function renderArticlePage(article, site) {
  const a = article ?? {};
  const slug = escapeHtml(a.slug);
  const url = `${SITE_ORIGIN}/articles/${slug}/`;
  const cover = safeAsset(a.cover);
  const title = (lang) => t(a.title, lang).trim();
  const desc = t(a.summary, 'th').trim();

  const side = (lang) => {
    const body = sanitizeRichText(t(a.body, lang));
    const summary = t(a.summary, lang).trim();
    return `    <article lang="${lang}" class="post">
      <p class="idx mono">${escapeHtml(a.date)}</p>
      <h1>${escapeHtml(title(lang))}</h1>
${summary ? `      <p class="post-lead">${escapeHtml(summary)}</p>\n` : ''}${cover ? `      <img class="post-cover" src="${escapeHtml(cover)}" alt="">\n` : ''}      <div class="post-body">${body}</div>
      ${tagList(a.tags)}
    </article>`;
  };

  const head = [
    `  <link rel="canonical" href="${url}">`,
    '  <meta property="og:type" content="article">',
    `  <meta property="og:title" content="${escapeHtml(title('th'))}">`,
    ...(desc ? [`  <meta property="og:description" content="${escapeHtml(desc)}">`] : []),
    `  <meta property="og:url" content="${url}">`,
    ...(cover ? [`  <meta property="og:image" content="${SITE_ORIGIN}${escapeHtml(cover)}">`] : []),
  ].join('\n');

  const main = `  <main id="main" class="doc">
${side('th')}
${side('en')}
    <p class="post-back"><a href="/articles/">&larr; ${both('allArticles')}</a></p>
  </main>`;

  return page({ titleTh: title('th'), titleEn: title('en'), description: desc, head, current: 'articles', site, main });
}

export function renderArticleList(articles, site) {
  const items = sortedPublished(articles);
  const label = (lang) => (lang === 'th' ? 'บทความ' : 'Articles');
  const head = `  <link rel="canonical" href="${SITE_ORIGIN}/articles/">
  <meta property="og:type" content="website">
  <meta property="og:title" content="${escapeHtml(label('th'))} | ${escapeHtml(siteName(site))}">
  <meta property="og:url" content="${SITE_ORIGIN}/articles/">`;

  const body = items.length
    ? `<ul class="art-list">${items.map((a) => {
      const slug = escapeHtml(a.slug);
      const both2 = (field) => ['th', 'en'].map((l) => {
        const v = t(field, l).trim();
        return v ? `<span lang="${l}">${escapeHtml(v)}</span>` : '';
      }).join('');
      const sum = both2(a.summary);
      return `
      <li class="art-item">
        <a href="/articles/${slug}/">
          <p class="idx mono">${escapeHtml(a.date)}</p>
          <h2>${both2(a.title)}</h2>
          ${sum ? `<p class="art-sum">${sum}</p>` : ''}
        </a>
        ${tagList(a.tags)}
      </li>`;
    }).join('')}
    </ul>`
    : `<div class="art-empty"><p class="art-empty-title">${both('empty')}</p><p class="muted">${both('emptyHint')}</p><p><a class="btn btn-ghost" href="/">${both('back')}</a></p></div>`;

  const main = `  <main id="main" class="doc">
    <header class="doc-head"><p class="idx mono">notes</p><h1>${both('articles')}</h1></header>
    ${body}
  </main>`;

  return page({ titleTh: label('th'), titleEn: label('en'), description: '', head, current: 'articles', site, main });
}
