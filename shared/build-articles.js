// Pure module (no DOM, no Node globals): the planning rules for generated article files.
// Used by tools/render-articles.mjs (writes to disk) and the Cloudflare Worker (commits to GitHub),
// so both produce byte-identical output.
import { validateArticle } from './schema.js';
import { renderArticlePage, renderArticleList, articleIndex } from './render-article.js';

/**
 * @param {object} site            parsed content/site.json
 * @param {{file: string, article: object}[]} entries  every article JSON (file = "<name>.json")
 * @param {{pages: Record<string, boolean>, list: boolean|null}} existing
 *        pages: slug -> true when articles/<slug>/index.html exists AND carries the generator marker
 *               (false = exists but hand-made); list: same for articles/index.html, null = absent
 * @returns {{errors: string[], files: Record<string,string>, removeSlugs: string[], deletePaths: string[]}}
 *   files: repo path -> content to write; removeSlugs: generated pages that no longer have a
 *   published article; deletePaths: the files to delete for them.
 */
export function planArticles(site, entries, existing = { pages: {}, list: null }) {
  const errors = [];
  const articles = [];
  for (const { file, article } of entries) {
    const v = validateArticle(article);
    if (!v.ok) v.errors.forEach((m) => errors.push(`${file}: ${m}`));
    else if (`${article.slug}.json` !== file) errors.push(`${file}: slug "${article.slug}" must match the file name`);
    else articles.push(article);
  }

  const published = articles.filter((a) => a.published);
  const slugs = new Set(published.map((a) => a.slug));
  for (const a of published) {
    if (existing.pages?.[a.slug] === false) errors.push(`articles/${a.slug}/index.html: exists and was not generated by render-articles, refusing to overwrite`);
  }
  if (existing.list === false) errors.push('articles/index.html: exists and was not generated by render-articles, refusing to overwrite');
  if (errors.length) return { errors, files: {}, removeSlugs: [], deletePaths: [] };

  const files = {};
  for (const a of published) files[`articles/${a.slug}/index.html`] = renderArticlePage(a, site);
  files['articles/index.html'] = renderArticleList(articles, site);
  files['content/articles/index.json'] = `${JSON.stringify(articleIndex(articles), null, 2)}\n`;

  const removeSlugs = Object.keys(existing.pages ?? {})
    .filter((slug) => existing.pages[slug] === true && !slugs.has(slug))
    .sort();
  return { errors: [], files, removeSlugs, deletePaths: removeSlugs.map((s) => `articles/${s}/index.html`) };
}
