import { test } from 'node:test';
import assert from 'node:assert/strict';
import { renderArticlePage, renderArticleList, articleIndex } from '../shared/render-article.js';

const SITE = { hero: { name: { th: 'วรยุทธ', en: 'Warayuth Bunbanlu' } } };
const BASE = 'https://warayuth014.github.io';

const art = (over = {}) => ({
  slug: 'hello-world',
  title: { th: 'สวัสดีโลก', en: 'Hello world' },
  summary: { th: 'สรุปไทย', en: 'English summary' },
  body: { th: '<p>เนื้อหาไทย</p>', en: '<p>English body</p>' },
  tags: ['a', 'b'],
  cover: null,
  date: '2026-10-24',
  published: true,
  ...over,
});

test('escapes <script> in the title and drops it from the body', () => {
  const html = renderArticlePage(art({
    title: { th: '<script>alert(1)</script>หัวข้อ', en: 'T <b>x</b>' },
    body: { th: '<p>ok</p><script>alert(2)</script>', en: '<p>ok</p>' },
  }), SITE);
  assert.ok(!html.includes('<script>alert'), 'no raw script from content');
  assert.ok(html.includes('&lt;script&gt;alert(1)&lt;/script&gt;หัวข้อ'));
  assert.ok(!html.includes('alert(2)'));
  assert.ok(html.includes('T &lt;b&gt;x&lt;/b&gt;'));
});

test('body sanitised: onerror image gone, javascript: link stripped', () => {
  const html = renderArticlePage(art({
    body: { th: '<p>x</p><img src=x onerror="alert(1)"><a href="javascript:alert(1)">bad</a>', en: '<a href="JaVa\tScript:alert(1)">e</a>' },
  }), SITE);
  assert.ok(!/onerror/i.test(html));
  assert.ok(!/javascript:/i.test(html));
  assert.ok(html.includes('bad'));
});

test('og:title uses the TH title by default; canonical and og:url carry the slug', () => {
  const html = renderArticlePage(art(), SITE);
  assert.match(html, /<html lang="th"/);
  assert.ok(html.includes('<meta property="og:title" content="สวัสดีโลก">'));
  assert.ok(html.includes(`<link rel="canonical" href="${BASE}/articles/hello-world/">`));
  assert.ok(html.includes(`<meta property="og:url" content="${BASE}/articles/hello-world/">`));
  assert.ok(html.includes('<meta name="description" content="สรุปไทย">'));
  assert.ok(html.includes('<article lang="th"') && html.includes('<article lang="en"'));
  assert.ok(html.includes('English body') && html.includes('เนื้อหาไทย'));
  assert.ok(html.includes('<!-- generated by render-articles -->'));
});

test('og:image absolute for a cover, absent when cover is null or unsafe', () => {
  const withCover = renderArticlePage(art({ cover: '/uploads/c.webp' }), SITE);
  assert.ok(withCover.includes(`<meta property="og:image" content="${BASE}/uploads/c.webp">`));
  assert.ok(!renderArticlePage(art(), SITE).includes('og:image'));
  assert.ok(!renderArticlePage(art({ cover: 'javascript:alert(1)' }), SITE).includes('og:image'));
  assert.ok(!renderArticlePage(art({ cover: '/uploads/../x' }), SITE).includes('og:image'));
});

test('empty EN side falls back to TH for title, summary and body', () => {
  const html = renderArticlePage(art({
    title: { th: 'ชื่อไทย', en: '' },
    summary: { th: 'สรุปไทยล้วน', en: '' },
    body: { th: '<p>เฉพาะไทย</p>', en: '' },
  }), SITE);
  const en = html.slice(html.indexOf('<article lang="en"'));
  assert.ok(en.includes('ชื่อไทย') && en.includes('เฉพาะไทย') && en.includes('สรุปไทยล้วน'));
});

test('TH side empty: default description and og:title fall back to EN', () => {
  const html = renderArticlePage(art({ title: { th: '', en: 'Only EN' }, summary: { th: '', en: 'EN sum' } }), SITE);
  assert.ok(html.includes('<meta property="og:title" content="Only EN">'));
  assert.ok(html.includes('<meta name="description" content="EN sum">'));
});

test('attribute values and tags are escaped', () => {
  const html = renderArticlePage(art({ title: { th: 'a" onload="x', en: 'b' }, tags: ['<i>t</i>'] }), SITE);
  assert.ok(!html.includes('onload="x'));
  assert.ok(html.includes('&lt;i&gt;t&lt;/i&gt;'));
});

test('list: published only, newest first, ties by slug, links to /articles/<slug>/', () => {
  const html = renderArticleList([
    art({ slug: 'old', date: '2026-01-01', title: { th: 'เก่า', en: 'Old' } }),
    art({ slug: 'draft', date: '2027-01-01', published: false, title: { th: 'ร่าง', en: 'Draft' } }),
    art({ slug: 'b-new', date: '2026-10-01', title: { th: 'ใหม่บี', en: 'NewB' } }),
    art({ slug: 'a-new', date: '2026-10-01', title: { th: 'ใหม่เอ', en: 'NewA' } }),
  ], SITE);
  assert.ok(!html.includes('draft'));
  const order = ['/articles/a-new/', '/articles/b-new/', '/articles/old/'].map((s) => html.indexOf(s));
  assert.ok(order.every((i) => i > -1) && order[0] < order[1] && order[1] < order[2]);
  assert.ok(html.includes('<!-- generated by render-articles -->'));
});

test('list: friendly empty state and escaping', () => {
  const empty = renderArticleList([art({ published: false })], SITE);
  assert.ok(empty.includes('เร็ว ๆ นี้') && empty.includes('Coming soon'));
  const xss = renderArticleList([art({ title: { th: '<script>x</script>', en: 'e' }, summary: { th: '<img src=x onerror=1>', en: 's' } })], SITE);
  assert.ok(!xss.includes('<script>x') && !xss.includes('<img src=x'));
});

test('articleIndex: published only, newest first, plain fields', () => {
  const idx = articleIndex([
    art({ slug: 'one', date: '2026-01-01' }),
    art({ slug: 'hidden', published: false, date: '2030-01-01' }),
    art({ slug: 'two', date: '2026-05-05', cover: '/uploads/c.png' }),
  ]);
  assert.deepEqual(idx.map((a) => a.slug), ['two', 'one']);
  assert.deepEqual(Object.keys(idx[0]).sort(), ['cover', 'date', 'slug', 'summary', 'tags', 'title']);
  assert.equal(idx[0].cover, '/uploads/c.png');
});
